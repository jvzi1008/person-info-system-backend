package com.ruoyi.compare.domain.vo;

public class TransferRow {
    private String idNo;
    private String name;
    private Integer zxlx;
    private String fromSchool;
    private String toSchool;
    private String applyTime;

    public String getIdNo() { return idNo; }
    public void setIdNo(String idNo) { this.idNo = idNo; }

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public Integer getZxlx() { return zxlx; }
    public void setZxlx(Integer zxlx) { this.zxlx = zxlx; }

    public String getFromSchool() { return fromSchool; }
    public void setFromSchool(String fromSchool) { this.fromSchool = fromSchool; }

    public String getToSchool() { return toSchool; }
    public void setToSchool(String toSchool) { this.toSchool = toSchool; }

    public String getApplyTime() { return applyTime; }
    public void setApplyTime(String applyTime) { this.applyTime = applyTime; }
}
